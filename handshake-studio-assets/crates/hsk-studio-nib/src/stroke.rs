//! Stroke outlining (lane SMB-NIB-VECTOR-RENDER slice 2; STU-VEC-006 outline stroke, STU-VEC-020,
//! STU-VEC-143 caps/joins/align, STU-VEC-144 weight and miter limit, STU-VEC-145 dashes).
//!
//! The stroke region follows the PostScript/SVG construction: the union of one rectangle per
//! flattened segment (width `w`, centred), one join shape per vertex where two segments meet, and
//! one cap shape per open end. Joins at real anchors use the style's join (miter while the miter
//! ratio `1 / cos(turn / 2)` is within `miter_limit`, else bevel; round; bevel); vertices created
//! by flattening a curve always get a round join, so curve offsets stay smooth. Every piece is
//! oriented to positive area on the shared integer grid and the pieces are united (non-zero) with
//! the Boolean engine ([`crate::boolean`]), so the result is a clean outline: polygons, outer
//! positive, holes negative, fill rule non-zero.
//!
//! Dashes: the pattern (odd-length lists repeat once, as SVG) is walked along each flattened subpath
//! by arc length from `phase`; every "on" interval becomes an open run with its own caps and joins.
//! A zero-length dash draws a cap-only dot (round/square caps) in the segment direction. The dash
//! count is bounded before any run is built. Corner adjustment (`adjust.dashes` etc.) is not built.
//!
//! Align: `Inside` strokes at twice the width and keeps the part inside the fill region, `Outside`
//! keeps the part outside it; both need every subpath closed (open subpaths are refused).
//!
//! Determinism: arcs are generated by repeated rotation with `cos a = 1 - tol / r` and
//! `sin a = sqrt(1 - cos^2)` (only IEEE-exact operations; no platform `sin`/`cos`/`atan2`).
//! Adobe's exact join/cap tessellation, the degenerate-dot direction and dash seam handling are
//! UNVERIFIED (D5).
#![deny(clippy::arithmetic_side_effects)]
use crate::boolean::{
    BooleanOptions, GeometryResult, Grid, Region, binary, candidate_guard, finish, normalise,
};
use crate::flatten::{Polyline, distance, flatten, norm};
use crate::owned_path::{COORDINATE_LIMIT, OwnedPath, PathPoint};
use crate::path_contract::Error;
use i_overlay::core::overlay_rule::OverlayRule;
use i_overlay::i_shape::int::shape::IntContour;

/// Largest number of dash/gap entries.
pub const MAX_DASH_ENTRIES: usize = 1024;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LineCap {
    Butt,
    Round,
    Square,
}
impl LineCap {
    /// Captured `stroke_cap` integers (STU-VEC-143): butt 1, round 2, projecting 3.
    pub const fn wire(self) -> u8 {
        match self {
            Self::Butt => 1,
            Self::Round => 2,
            Self::Square => 3,
        }
    }
    pub fn from_wire(value: u8) -> Result<Self, Error> {
        match value {
            1 => Ok(Self::Butt),
            2 => Ok(Self::Round),
            3 => Ok(Self::Square),
            _ => Err(Error::InvalidEncoding),
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LineJoin {
    Miter,
    Round,
    Bevel,
}
impl LineJoin {
    /// Captured `stroke_join` integers (STU-VEC-143): miter 1, round 2, bevel 3.
    pub const fn stroke_wire(self) -> u8 {
        match self {
            Self::Miter => 1,
            Self::Round => 2,
            Self::Bevel => 3,
        }
    }
    pub fn from_stroke_wire(value: u8) -> Result<Self, Error> {
        match value {
            1 => Ok(Self::Miter),
            2 => Ok(Self::Round),
            3 => Ok(Self::Bevel),
            _ => Err(Error::InvalidEncoding),
        }
    }
    /// Captured offset-path `joins` integers (STU-VEC-113): miter 0, round 1, bevel 2.
    pub const fn offset_wire(self) -> u8 {
        match self {
            Self::Miter => 0,
            Self::Round => 1,
            Self::Bevel => 2,
        }
    }
    pub fn from_offset_wire(value: u8) -> Result<Self, Error> {
        match value {
            0 => Ok(Self::Miter),
            1 => Ok(Self::Round),
            2 => Ok(Self::Bevel),
            _ => Err(Error::InvalidEncoding),
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum StrokeAlign {
    Center,
    Inside,
    Outside,
}
impl StrokeAlign {
    /// Captured `stroke_align` tokens (STU-VEC-143).
    pub const fn wire(self) -> &'static str {
        match self {
            Self::Center => "CENTER",
            Self::Inside => "INSIDE",
            Self::Outside => "OUTSIDE",
        }
    }
    pub fn parse(text: &str) -> Result<Self, Error> {
        match text {
            "CENTER" => Ok(Self::Center),
            "INSIDE" => Ok(Self::Inside),
            "OUTSIDE" => Ok(Self::Outside),
            _ => Err(Error::InvalidEncoding),
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub struct DashPattern {
    /// Alternating dash and gap lengths, dash first (STU-VEC-145: unbounded array, stored as given).
    pub lengths: Vec<f64>,
    /// Distance into the pattern at the start of every subpath.
    pub phase: f64,
}

#[derive(Clone, Debug, PartialEq)]
pub struct StrokeStyle {
    pub width: f64,
    pub cap: LineCap,
    pub join: LineJoin,
    /// Ratio of miter length to stroke width; STU-VEC-144 hard range 1..=500.
    pub miter_limit: f64,
    pub dash: Option<DashPattern>,
    pub align: StrokeAlign,
}
impl StrokeStyle {
    pub fn new(width: f64) -> Self {
        Self {
            width,
            cap: LineCap::Butt,
            join: LineJoin::Miter,
            miter_limit: 4.0,
            dash: None,
            align: StrokeAlign::Center,
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct StrokeOptions {
    /// Flattening, grid and sweep budgets; `geometry.flatten.tolerance` is also the arc tolerance of
    /// round joins and caps.
    pub geometry: BooleanOptions,
    /// Largest number of pieces (segment rectangles, joins, caps, dash runs).
    pub max_pieces: usize,
}
impl Default for StrokeOptions {
    fn default() -> Self {
        Self {
            geometry: BooleanOptions::default(),
            max_pieces: 1 << 18,
        }
    }
}

/// Outline of `path` stroked with `style`: filled geometry of the painted stroke area.
pub fn outline_stroke(
    path: &OwnedPath,
    style: &StrokeStyle,
    options: &StrokeOptions,
) -> Result<GeometryResult, Error> {
    check_style(style)?;
    let lines = flatten(path, &options.geometry.flatten)?;
    let width = match style.align {
        StrokeAlign::Center => style.width,
        StrokeAlign::Inside | StrokeAlign::Outside => {
            if lines.iter().any(|l| !l.closed) {
                return Err(Error::UnsupportedOptions);
            }
            style.width * 2.0
        }
    };
    let mut builder = Builder {
        half: width * 0.5,
        tolerance: options.geometry.flatten.tolerance,
        style,
        pieces: Vec::new(),
        max_pieces: options.max_pieces,
        points: 0,
        max_points: options.geometry.flatten.max_points,
    };
    let runs = match &style.dash {
        Some(dash) => dashes(&lines, dash, options.max_pieces)?,
        None => lines.iter().map(Run::whole).collect(),
    };
    for run in &runs {
        builder.run(run)?;
    }
    let pieces = std::mem::take(&mut builder.pieces);
    let grid = Grid::covering(pieces.iter().chain(lines.iter()))?;
    let pairs = candidate_guard(pieces.iter(), &grid, &options.geometry)?;
    let contours: Vec<IntContour> = grid
        .contours(&pieces)
        .into_iter()
        .filter_map(orient_positive)
        .collect();
    let mut shapes = normalise(&contours, crate::owned_path::FillRule::NonZero);
    if style.align != StrokeAlign::Center {
        let fill = normalise(&grid.contours(&lines), path.fill_rule);
        let rule = if style.align == StrokeAlign::Inside {
            OverlayRule::Intersect
        } else {
            OverlayRule::Difference
        };
        shapes = binary(&shapes, &fill, rule);
    }
    let region = [Region {
        lines: pieces,
        fill_rule: crate::owned_path::FillRule::NonZero,
    }];
    finish(shapes, &grid, options.geometry.flatten.tolerance, &region, pairs)
}

fn check_style(style: &StrokeStyle) -> Result<(), Error> {
    if !style.width.is_finite() || style.width <= 0.0 || style.width > COORDINATE_LIMIT {
        return Err(Error::UnsupportedOptions);
    }
    if !style.miter_limit.is_finite() || !(1.0..=500.0).contains(&style.miter_limit) {
        return Err(Error::UnsupportedOptions);
    }
    if let Some(dash) = &style.dash {
        if dash.lengths.is_empty() || dash.lengths.len() > MAX_DASH_ENTRIES {
            return Err(Error::UnsupportedOptions);
        }
        if !dash.phase.is_finite() || dash.phase.abs() > COORDINATE_LIMIT {
            return Err(Error::UnsupportedOptions);
        }
        let mut total = 0.0;
        for v in &dash.lengths {
            if !v.is_finite() || *v < 0.0 || *v > COORDINATE_LIMIT {
                return Err(Error::UnsupportedOptions);
            }
            total += v;
        }
        if total <= 0.0 {
            return Err(Error::UnsupportedOptions);
        }
    }
    Ok(())
}

/// Integer shoelace twice-area sign; reversed when negative, dropped when zero.
fn orient_positive(mut contour: IntContour) -> Option<IntContour> {
    let mut twice: i128 = 0;
    let next = contour.iter().cycle().skip(1);
    for (a, b) in contour.iter().zip(next) {
        let cross = i128::from(a.x)
            .saturating_mul(i128::from(b.y))
            .saturating_sub(i128::from(b.x).saturating_mul(i128::from(a.y)));
        twice = twice.saturating_add(cross);
    }
    match twice.signum() {
        1 => Some(contour),
        -1 => {
            contour.reverse();
            Some(contour)
        }
        _ => None,
    }
}

/// One stroked run: a polyline (dash or whole subpath) and, for a zero-length run, its direction.
struct Run {
    points: Vec<PathPoint>,
    anchors: Vec<bool>,
    closed: bool,
    direction: Option<(f64, f64)>,
}
impl Run {
    fn whole(line: &Polyline) -> Self {
        Self {
            points: line.points.clone(),
            anchors: line.anchors.clone(),
            closed: line.closed && line.points.len() > 2,
            direction: None,
        }
    }
}

struct Builder<'a> {
    half: f64,
    tolerance: f64,
    style: &'a StrokeStyle,
    pieces: Vec<Polyline>,
    max_pieces: usize,
    points: usize,
    max_points: usize,
}

fn unit(a: PathPoint, b: PathPoint) -> Option<(f64, f64)> {
    let (dx, dy) = (b.x - a.x, b.y - a.y);
    let len = norm(dx, dy);
    if len > 0.0 && len.is_finite() {
        Some((dx / len, dy / len))
    } else {
        None
    }
}

fn at(p: PathPoint, dx: f64, dy: f64) -> PathPoint {
    PathPoint::new(p.x + dx, p.y + dy)
}

impl Builder<'_> {
    fn piece(&mut self, points: Vec<PathPoint>) -> Result<(), Error> {
        if self.pieces.len() >= self.max_pieces {
            return Err(Error::BudgetExceeded);
        }
        self.points = self
            .points
            .checked_add(points.len())
            .ok_or(Error::BudgetExceeded)?;
        if self.points > self.max_points {
            return Err(Error::BudgetExceeded);
        }
        let anchors = vec![false; points.len()];
        self.pieces.push(Polyline {
            points,
            anchors,
            closed: true,
        });
        Ok(())
    }


    fn run(&mut self, run: &Run) -> Result<(), Error> {
        let h = self.half;
        // Distinct segments: (start, end, unit direction, index of the end point).
        let mut segs: Vec<(PathPoint, PathPoint, (f64, f64), usize)> = Vec::new();
        for (i, w) in run.points.windows(2).enumerate() {
            if let Some(d) = unit(w[0], w[1]) {
                segs.push((w[0], w[1], d, i.saturating_add(1)));
            }
        }
        if run.closed
            && let (Some(&last), Some(&first)) = (run.points.last(), run.points.first())
            && let Some(d) = unit(last, first)
        {
            segs.push((last, first, d, 0));
        }
        if segs.is_empty() {
            // Zero-length run: a dot from the caps (butt draws nothing).
            let Some(&c) = run.points.first() else {
                return Ok(());
            };
            let (dx, dy) = run.direction.unwrap_or((1.0, 0.0));
            return match self.style.cap {
                LineCap::Butt => Ok(()),
                LineCap::Square => self.piece(vec![
                    at(c, (dx + dy) * h, (dy - dx) * h),
                    at(c, (dx - dy) * h, (dy + dx) * h),
                    at(c, (-dx - dy) * h, (-dy + dx) * h),
                    at(c, (-dx + dy) * h, (-dy - dx) * h),
                ]),
                LineCap::Round => {
                    let mut pts = self.arc(c, (-dy, dx), (dy, -dx), false)?;
                    let back = self.arc(c, (dy, -dx), (-dy, dx), false)?;
                    pts.extend(back);
                    self.piece(pts)
                }
            };
        }
        for &(a, b, (dx, dy), _) in &segs {
            let (nx, ny) = (-dy * h, dx * h);
            self.piece(vec![
                at(a, nx, ny),
                at(b, nx, ny),
                at(b, -nx, -ny),
                at(a, -nx, -ny),
            ])?;
        }
        // Joins between consecutive segments (and across the seam of a closed run).
        let mut previous = if run.closed { segs.last().copied() } else { None };
        for &seg in &segs {
            if let Some((_, v, d0, end)) = previous {
                let anchor = run.anchors.get(end).copied().unwrap_or(false);
                self.join(v, d0, seg.2, anchor)?;
            }
            previous = Some(seg);
        }
        if !run.closed
            && let (Some(&(a, _, d, _)), Some(&(_, b, e, _))) = (segs.first(), segs.last())
        {
            self.cap(a, (-d.0, -d.1))?;
            self.cap(b, e)?;
        }
        Ok(())
    }

    fn join(
        &mut self,
        v: PathPoint,
        d0: (f64, f64),
        d1: (f64, f64),
        anchor: bool,
    ) -> Result<(), Error> {
        let h = self.half;
        let cross = d0.0 * d1.1 - d0.1 * d1.0;
        let dot = d0.0 * d1.0 + d0.1 * d1.1;
        if cross == 0.0 && dot > 0.0 {
            return Ok(()); // straight continuation
        }
        // Outer side: right of travel for a left turn (cross > 0, y up), left for a right turn.
        let s = if cross > 0.0 { -1.0 } else { 1.0 };
        let u0 = (-d0.1 * s, d0.0 * s);
        let u1 = (-d1.1 * s, d1.0 * s);
        let (p0, p1) = (at(v, u0.0 * h, u0.1 * h), at(v, u1.0 * h, u1.1 * h));
        let join = if anchor {
            self.style.join
        } else {
            LineJoin::Round
        };
        match join {
            LineJoin::Bevel => self.piece(vec![v, p0, p1]),
            LineJoin::Miter => {
                let limit = self.style.miter_limit;
                // miter ratio^2 = 2 / (1 + cos turn); within the limit while <= limit^2.
                if 1.0 + dot > 0.0 && 2.0 / (1.0 + dot) <= limit * limit {
                    let k = h / (1.0 + dot);
                    let m = at(v, (u0.0 + u1.0) * k, (u0.1 + u1.1) * k);
                    self.piece(vec![v, p0, m, p1])
                } else {
                    self.piece(vec![v, p0, p1])
                }
            }
            LineJoin::Round => {
                // Normals turn the same way as the travel direction: counter-clockwise on a left turn.
                let mut pts = vec![v];
                pts.extend(self.arc(v, u0, u1, cross > 0.0)?);
                self.piece(pts)
            }
        }
    }

    fn cap(&mut self, p: PathPoint, d: (f64, f64)) -> Result<(), Error> {
        let h = self.half;
        let n = (-d.1, d.0);
        match self.style.cap {
            LineCap::Butt => Ok(()),
            LineCap::Square => self.piece(vec![
                at(p, n.0 * h, n.1 * h),
                at(p, -n.0 * h, -n.1 * h),
                at(p, (d.0 - n.0) * h, (d.1 - n.1) * h),
                at(p, (d.0 + n.0) * h, (d.1 + n.1) * h),
            ]),
            LineCap::Round => {
                // Half circle from +n through +d to -n: clockwise with y up.
                let pts = self.arc(p, n, (-n.0, -n.1), false)?;
                self.piece(pts)
            }
        }
    }

    /// Points on the circle of radius `half` around `c` from unit vector `u0` to `u1` (both
    /// included), turning counter-clockwise when `ccw` (y up), else clockwise; the sweep is at most a
    /// half turn. The step angle `a` has `cos a = 1 - tol / r`, so every chord's sagitta is within the
    /// tolerance. A point at angle `t` from `u0` (0 <= t <= pi) is before `u1` exactly when it lies in
    /// the half plane of the turn and its dot product with `u0` exceeds `u0 . u1` (cos decreases).
    fn arc(
        &mut self,
        c: PathPoint,
        u0: (f64, f64),
        u1: (f64, f64),
        ccw: bool,
    ) -> Result<Vec<PathPoint>, Error> {
        let h = self.half;
        let cos_a = (1.0 - self.tolerance / h).max(0.0);
        let sin_abs = (1.0 - cos_a * cos_a).max(0.0).sqrt();
        let (sin_a, turn) = if ccw { (sin_abs, 1.0) } else { (-sin_abs, -1.0) };
        let target = u0.0 * u1.0 + u0.1 * u1.1;
        let mut out = vec![at(c, u0.0 * h, u0.1 * h)];
        let mut u = u0;
        loop {
            let next = (u.0 * cos_a - u.1 * sin_a, u.0 * sin_a + u.1 * cos_a);
            let side = turn * (u0.0 * next.1 - u0.1 * next.0);
            let along = u0.0 * next.0 + u0.1 * next.1;
            if side < 0.0 || along <= target {
                break;
            }
            if out.len() >= self.max_points {
                return Err(Error::BudgetExceeded);
            }
            u = next;
            out.push(at(c, u.0 * h, u.1 * h));
        }
        out.push(at(c, u1.0 * h, u1.1 * h));
        Ok(out)
    }
}

fn next_index(index: usize, len: usize) -> usize {
    let next = index.saturating_add(1);
    if next >= len { 0 } else { next }
}

/// Splits polylines into dash runs (open). The number of runs is bounded before any is built.
fn dashes(lines: &[Polyline], dash: &DashPattern, max_pieces: usize) -> Result<Vec<Run>, Error> {
    let mut pattern = dash.lengths.clone();
    if pattern.len() & 1 == 1 {
        pattern.extend_from_slice(&dash.lengths);
    }
    let period: f64 = pattern.iter().sum();
    let total: f64 = lines.iter().map(Polyline::length).sum();
    // Every line restarts the pattern: at most (length / period + 1) periods of `len` entries each.
    let entries = pattern.len() as f64;
    let bound = (total / period + lines.len() as f64) * entries;
    if !bound.is_finite() || bound > max_pieces as f64 {
        return Err(Error::BudgetExceeded);
    }
    let mut runs: Vec<Run> = Vec::new();
    let mut boundaries = 0usize;
    // Hard stop for the walk itself, independent of float accumulation.
    let max_boundaries = max_pieces.saturating_mul(2).saturating_add(pattern.len());
    for line in lines {
        let mut verts: Vec<(PathPoint, bool)> = line
            .points
            .iter()
            .copied()
            .zip(line.anchors.iter().copied())
            .collect();
        if line.closed
            && let Some(first) = verts.first().copied()
        {
            verts.push(first);
        }
        let Some(&(start, start_anchor)) = verts.first() else {
            continue;
        };
        // Pattern state at the phase.
        let mut phase = dash.phase % period;
        if phase < 0.0 {
            phase += period;
        }
        let mut index = 0usize;
        let mut skipped = 0usize;
        while phase > 0.0 && phase >= pattern[index] && skipped < pattern.len() {
            phase -= pattern[index];
            index = next_index(index, pattern.len());
            skipped = skipped.saturating_add(1);
        }
        let mut left = (pattern[index] - phase).max(0.0);
        let mut current = (index & 1 == 0).then(|| Run {
            points: vec![start],
            anchors: vec![start_anchor],
            closed: false,
            direction: None,
        });
        for w in verts.windows(2) {
            let ((a, _), (b, b_anchor)) = (w[0], w[1]);
            let len = distance(a, b);
            let dir = unit(a, b);
            let mut pos = 0.0;
            while left <= len - pos {
                boundaries = boundaries.saturating_add(1);
                if boundaries > max_boundaries {
                    return Err(Error::BudgetExceeded);
                }
                pos += left;
                let t = if len > 0.0 { (pos / len).min(1.0) } else { 0.0 };
                let q = PathPoint::new(a.x + (b.x - a.x) * t, a.y + (b.y - a.y) * t);
                if let Some(mut run) = current.take() {
                    if run.points.last() != Some(&q) {
                        run.points.push(q);
                        run.anchors.push(false);
                    }
                    run.direction = dir;
                    if runs.len() >= max_pieces {
                        return Err(Error::BudgetExceeded);
                    }
                    runs.push(run);
                }
                index = next_index(index, pattern.len());
                left = pattern[index];
                current = (index & 1 == 0).then(|| Run {
                    points: vec![q],
                    anchors: vec![false],
                    closed: false,
                    direction: dir,
                });
            }
            left -= len - pos;
            if let Some(run) = current.as_mut() {
                if run.points.last() != Some(&b) {
                    run.points.push(b);
                    run.anchors.push(b_anchor);
                }
                if run.direction.is_none() {
                    run.direction = dir;
                }
            }
        }
        // A dash that only starts at the very end of the subpath has no length yet: it is not a
        // zero-length dash entry and draws nothing (no end-cap dot).
        if let Some(run) = current.take()
            && (run.points.len() > 1 || pattern[index] == 0.0)
        {
            if runs.len() >= max_pieces {
                return Err(Error::BudgetExceeded);
            }
            runs.push(run);
        }
    }
    Ok(runs)
}
