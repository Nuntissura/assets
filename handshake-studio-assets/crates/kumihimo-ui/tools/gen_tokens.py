"""Generates src/tokens.rs from design/design-system.json (design step B0). Run from anywhere:

    python crates/kumihimo-ui/tools/gen_tokens.py

design/design-system.json is a byte copy of the GUI designer's authority file (kernel S/gui-design/design-system.json);
refresh the copy, then rerun this script. tests/tokens.rs fails when the copy and the generated file disagree.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "design-system.json"
OUT = ROOT / "src" / "tokens.rs"


def fnv64(data: bytes) -> int:
    h = 0xCBF29CE484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def ident(name: str) -> str:
    return "".join(p.capitalize() for p in name.replace(".", "_").split("_"))


def const(name: str) -> str:
    return name.replace(".", "_").upper()


def rgba(hexs: str) -> str:
    h = hexs.lstrip("#")
    if len(h) == 6:
        h += "FF"
    assert len(h) == 8, hexs
    r, g, b, a = (int(h[i : i + 2], 16) for i in range(0, 8, 2))
    return f"Rgba8::new({r}, {g}, {b}, {a})"


def main() -> None:
    raw = SRC.read_bytes()
    d = json.loads(raw)
    col = d["color"]
    dark, light, fixed = col["themes"]["dark"], col["themes"]["light"], col["fixed"]
    assert set(dark) == set(light), "dark and light themes name the same tokens"
    themed = list(dark)
    names = themed + list(fixed)
    o = []
    w = o.append
    w("// @generated by tools/gen_tokens.py from design/design-system.json. Do not edit; rerun the generator.")
    w("//! Design tokens (design step B0). Every colour, size and text style a widget uses is named here; UI code never")
    w("//! types a colour or size literal (tests/tokens.rs `ui_source_has_no_colour_literal`).")
    w("#![allow(clippy::unreadable_literal)]")
    w("use crate::geom::Rgba8;")
    w("")
    w(f'/// FNV-1a 64 of the design-system.json bytes this file was generated from.')
    w(f"pub const SOURCE_FNV64: u64 = 0x{fnv64(raw):016X};")
    w(f'pub const SOURCE_SPEC_VERSION: &str = "{d["spec_version"]}";')
    w("")
    w("/// The active theme. Fixed tokens resolve the same in both.")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]")
    w("pub enum Theme {\n    Dark,\n    Light,\n}")
    w("")
    w("/// Every colour token by dotted name: themed tokens first, then the fixed table.")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]")
    w("pub enum ColorToken {")
    for n in names:
        w(f"    {ident(n)},")
    w("}")
    w("")
    w("impl ColorToken {")
    w("    pub const ALL: &'static [ColorToken] = &[")
    for n in names:
        w(f"        ColorToken::{ident(n)},")
    w("    ];")
    w(f"    /// Tokens before this index are themed.")
    w(f"    pub const THEMED: usize = {len(themed)};")
    w("    pub fn name(self) -> &'static str {")
    w("        match self {")
    for n in names:
        w(f'            ColorToken::{ident(n)} => "{n}",')
    w("        }")
    w("    }")
    w("    pub fn from_name(name: &str) -> Option<ColorToken> {")
    w("        Self::ALL.iter().copied().find(|t| t.name() == name)")
    w("    }")
    w("    pub fn resolve(self, theme: Theme) -> Rgba8 {")
    w("        match (self, theme) {")
    for n in themed:
        w(f"            (ColorToken::{ident(n)}, Theme::Dark) => {rgba(dark[n])},")
        w(f"            (ColorToken::{ident(n)}, Theme::Light) => {rgba(light[n])},")
    for n in fixed:
        w(f"            (ColorToken::{ident(n)}, _) => {rgba(fixed[n])},")
    w("        }")
    w("    }")
    w("}")
    w("")
    w("/// Logical px at scale 1 (design-system.json `size`).")
    w("pub mod size {")
    for k, v in d["size"].items():
        w(f"    pub const {const(k)}: f32 = {float(v)!r};")
    w("    pub const TABLE: &[(&str, f32)] = &[")
    for k in d["size"]:
        w(f'        ("{k}", {const(k)}),')
    w("    ];")
    w("}")
    w("")
    for sect in ("spacing", "radius", "stroke"):
        table = d[sect]["tokens"] if sect == "spacing" else d[sect]
        w(f"/// design-system.json `{sect}`, logical px.")
        w(f"pub mod {sect} {{")
        for k, v in table.items():
            w(f"    pub const {const(k)}: f32 = {float(v)!r};")
        w("    pub const TABLE: &[(&str, f32)] = &[")
        for k in table:
            w(f'        ("{k}", {const(k)}),')
        w("    ];")
        w("}")
        w("")
    w("/// A text style of design-system.json `type.styles`.")
    w("#[derive(Clone, Copy, Debug, PartialEq)]")
    w("pub struct TextStyle {")
    w("    pub token: TextToken,\n    pub size: f32,\n    pub line: f32,\n    pub weight: u16,\n    pub tracking: f32,")
    w("    /// Tabular figures (`tnum`).\n    pub tnum: bool,\n    /// Code family (`mono`).\n    pub mono: bool,")
    w("}")
    styles = d["type"]["styles"]
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]")
    w("pub enum TextToken {")
    for k in styles:
        w(f"    {ident(k)},")
    w("}")
    w("impl TextToken {")
    w("    pub const ALL: &'static [TextToken] = &[")
    for k in styles:
        w(f"        TextToken::{ident(k)},")
    w("    ];")
    w("    pub fn name(self) -> &'static str {\n        match self {")
    for k in styles:
        w(f'            TextToken::{ident(k)} => "{k}",')
    w("        }\n    }")
    w("    pub fn style(self) -> TextStyle {\n        match self {")
    for k, s in styles.items():
        tnum = "true" if "tnum" in s.get("features", []) else "false"
        mono = "true" if s.get("family") == "code" else "false"
        w(
            f"            TextToken::{ident(k)} => TextStyle {{ token: TextToken::{ident(k)}, size: {float(s['size'])!r}, "
            f"line: {float(s['line'])!r}, weight: {int(s['weight'])}, tracking: {float(s.get('tracking', 0.0))!r}, "
            f"tnum: {tnum}, mono: {mono} }},"
        )
    w("        }\n    }")
    w("}")
    w("")
    # Interaction state table: colour-valued keys only.
    inter = d["state"]["interaction"]
    keys = ["fill", "text", "icon", "unit", "secondary", "hot_point", "edge_left_2", "edge_top_2", "edge_bottom_1",
            "edge_bottom_2", "gutter_left_2", "ring", "halo", "caret", "selection_bg", "drop_edge_2"]
    w("/// One resolved state of design-system.json `state.interaction`: colour slots only (None = absent or transparent).")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]")
    w("pub struct StateStyle {")
    for k in keys:
        w(f"    pub {k}: Option<ColorToken>,")
    w("    /// Ring width (logical px) when the state draws a ring.\n    pub ring_w: u8,\n    /// Ring drawn inside the rect (rows, tabs, slots).\n    pub inset: bool,")
    w("    /// Weight override of the text style (tab active: 600).\n    pub weight: u16,")
    w("}")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]")
    w("pub enum StyleKind {")
    for k in inter:
        w(f"    {ident(k)},")
    w("}")
    states = sorted({s for v in inter.values() for s in v})
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]")
    w("pub enum State {")
    for s in states:
        w(f"    {ident(s)},")
    w("}")
    w("/// The state record, or None when the kind does not define that state.")
    w("pub fn state_style(kind: StyleKind, state: State) -> Option<StateStyle> {")
    w("    match (kind, state) {")
    for k, v in inter.items():
        for s, m in v.items():
            fields = []
            for key in keys:
                val = m.get(key)
                if isinstance(val, str) and val != "transparent":
                    assert val in names, (k, s, key, val)
                    fields.append(f"{key}: Some(ColorToken::{ident(val)})")
            if "ring_w" in m:
                fields.append(f"ring_w: {int(m['ring_w'])}")
            if m.get("inset"):
                fields.append("inset: true")
            if "weight" in m:
                fields.append(f"weight: {int(m['weight'])}")
            body = ", ".join(fields + ["..StateStyle::EMPTY"])
            w(f"        (StyleKind::{ident(k)}, State::{ident(s)}) => Some(StateStyle {{ {body} }}),")
    w("        _ => None,")
    w("    }")
    w("}")
    w("impl StateStyle {")
    w("    pub const EMPTY: StateStyle = StateStyle {")
    for k in keys:
        w(f"        {k}: None,")
    w("        ring_w: 0,\n        inset: false,\n        weight: 0,\n    };")
    w("}")
    w("")
    OUT.write_text("\n".join(o) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(names)} colours, {len(d['size'])} sizes, {len(styles)} text styles")


if __name__ == "__main__":
    main()
