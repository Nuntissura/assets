"""Generates src/icon_data.rs from design/icons.json (design step B3, icon half). Run from anywhere:

    python crates/kumihimo-ui/tools/gen_icons.py
    python crates/kumihimo-ui/tools/gen_icons.py --from <kernel>/.GOV/docs_repo/wp-studio-module-work/gui-design/tools/mock_icons.py

design/icons.json is a copy of the TOOL and UI path data of the GUI designer's icon set (kernel
S/gui-design/tools/mock_icons.py), with that file's kernel-relative path and FNV-1a 64 of its bytes. `--from` refreshes the
copy from the designer's file (read with ast.literal_eval, never imported or executed), then the Rust table is written.
tests/icons.rs fails when the copy and the generated file disagree.
"""
import ast
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "icons.json"
OUT = ROOT / "src" / "icon_data.rs"
KERNEL_REL = ".GOV/docs_repo/wp-studio-module-work/gui-design/tools/mock_icons.py"


def fnv64(data: bytes) -> int:
    h = 0xCBF29CE484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def literal(tree: ast.Module, name: str):
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise SystemExit(f"gen_icons: {name} not found in the designer's file")


def refresh(path: pathlib.Path) -> None:
    raw = path.read_bytes()
    tree = ast.parse(raw.decode("utf-8"))
    tool = literal(tree, "TOOL")
    ui = literal(tree, "UI")
    doc = {
        "schema": "kumihimo.ui.icons@1",
        "source": KERNEL_REL,
        "source_fnv64": f"0x{fnv64(raw):016X}",
        "provenance": "original to this kit (design-system.json icon.provenance); designer's icon set copied verbatim",
        "tool": {"grid": 20, "stroke": 1.5, "hot_point": {"size": 3, "corner": 0.6}, "icons": {k: {"d": d, "hot": [hx, hy]} for k, (d, hx, hy) in tool.items()}},
        "ui": {"grid": 16, "stroke": 1.25, "icons": {k: {"d": d} for k, d in ui.items()}},
    }
    SRC.write_text(json.dumps(doc, indent=1, ensure_ascii=True) + "\n", encoding="utf-8", newline="\n")


def rs_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=True)


def rs_f32(v) -> str:
    t = repr(float(v))
    return t


def main() -> None:
    args = sys.argv[1:]
    if args[:1] == ["--from"] and len(args) == 2:
        refresh(pathlib.Path(args[1]))
    elif args:
        raise SystemExit("usage: gen_icons.py [--from mock_icons.py]")
    raw = SRC.read_bytes()
    d = json.loads(raw)
    o = []
    w = o.append
    w("// @generated by tools/gen_icons.py from design/icons.json. Do not edit; rerun the generator.")
    w("//! The designer's icon path data (tool icons on a 20 grid with a hot point, panel icons on a 16 grid).")
    w("")
    w("/// FNV-1a 64 of the design/icons.json bytes this file was generated from.")
    w(f"pub const SOURCE_FNV64: u64 = 0x{fnv64(raw):016X};")
    w("/// Kernel-relative path of the designer's file the copy came from, and FNV-1a 64 of its bytes.")
    w(f"pub const DESIGN_SOURCE: &str = {rs_str(d['source'])};")
    w(f"pub const DESIGN_SOURCE_FNV64: u64 = {d['source_fnv64']};")
    w(f"pub const TOOL_GRID: f32 = {rs_f32(d['tool']['grid'])};")
    w(f"pub const TOOL_STROKE: f32 = {rs_f32(d['tool']['stroke'])};")
    w(f"pub const HOT_POINT: f32 = {rs_f32(d['tool']['hot_point']['size'])};")
    w(f"pub const HOT_CORNER: f32 = {rs_f32(d['tool']['hot_point']['corner'])};")
    w(f"pub const UI_GRID: f32 = {rs_f32(d['ui']['grid'])};")
    w(f"pub const UI_STROKE: f32 = {rs_f32(d['ui']['stroke'])};")
    w("/// (name, path d, hot point x, y) in grid units, in the designer's order.")
    w("pub static TOOL: &[(&str, &str, f32, f32)] = &[")
    for k, v in d["tool"]["icons"].items():
        w(f"    ({rs_str(k)}, {rs_str(v['d'])}, {rs_f32(v['hot'][0])}, {rs_f32(v['hot'][1])}),")
    w("];")
    w("/// (name, path d) in grid units, in the designer's order.")
    w("pub static UI: &[(&str, &str)] = &[")
    for k, v in d["ui"]["icons"].items():
        w(f"    ({rs_str(k)}, {rs_str(v['d'])}),")
    w("];")
    OUT.write_text("\n".join(o) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {len(d['tool']['icons'])} tool, {len(d['ui']['icons'])} ui")


if __name__ == "__main__":
    main()
