//! Hand-written adversarial inputs. Every group names the HTML Standard section its inputs exercise
//! (https://html.spec.whatwg.org/multipage/parsing.html).

pub type Cases = Vec<(String, String)>;

fn labelled(group: &str, inputs: &[&str]) -> Cases {
    inputs
        .iter()
        .enumerate()
        .map(|(i, s)| (format!("{group}#{i}"), (*s).to_owned()))
        .collect()
}

