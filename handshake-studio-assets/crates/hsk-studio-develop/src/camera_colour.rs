//! Camera colour for proprietary raw frames (lane SMB-DEVELOP-CAMERA-COLOUR): the DNG colour tags a
//! vendor container does not carry, built so [`crate::color::solve`] runs unchanged.
//!
//! Sources, in order of preference:
//! 1. **The file's own matrix** ([`FileMatrix`]): a vendor tag holding the camera's white-balanced
//!    camera RGB -> output RGB matrix (Olympus maker note 0x1011, rows summing to 256). It is read as
//!    white-balanced camera -> linear sRGB (D65) and becomes one D65 calibration:
//!    ForwardMatrix = SRGB_TO_XYZ_D50 . M (rows normalised to 1), ColorMatrix = diag(as-shot neutral)
//!    . inverse(Bradford(D50 -> D65) . ForwardMatrix). The as-shot render (ForwardMatrix path) uses
//!    only the file's numbers; the ColorMatrix places the as-shot white at D65, so a kelvin/tint
//!    re-solve treats the as-shot light as D65 (named `file_matrix_white_assumed_d65`).
//! 2. **A spectral table** ([`SpectralCamera`], `camera_table.rs`, generated by
//!    `tools/camera-matrix-table.py`): ColorMatrix1/2 and ForwardMatrix1/2 (Standard Illuminant A and
//!    D65) fitted to measured camera spectral sensitivities from rawtoaces-data (Academy Software
//!    Foundation, Apache-2.0), looked up by make and model, then by rawtoaces-data's own aliases.
//! 3. **None**: the frame keeps only its as-shot neutral and `solve` refuses `missing_colour_data`.
//!
//! The as-shot neutral is always the file's (vendor white-balance tag, read by each decoder). No
//! matrix comes from Adobe, dcraw, LibRaw or rawspeed.
// V4-01: lookups over decoder-provided strings and numbers only; no integer arithmetic.
#![deny(clippy::arithmetic_side_effects)]
use crate::color::{self, D50_XYZ, DngColor, Mat3, SRGB_TO_XYZ_D50};

#[path = "camera_table.rs"]
mod table;

/// Loss note of an opted-in single-illuminant colour route (lane SMB-DEVELOP-CAMERA-COLOUR-2).
pub const APPROXIMATE_COLOUR_LOSS: &str = "approximate_colour_single_illuminant";

/// DNG CalibrationIlluminant codes of the table matrices: Standard light A, D65.
const TABLE_ILLUMINANTS: [u16; 2] = [17, 21];
/// D65 white (XYZ, Y = 1), the white of the file-matrix calibration.
const D65_XYZ: [f64; 3] = [0.95047, 1.0, 1.08883];

/// One camera of the spectral table (row-major matrices).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct SpectralCamera {
    pub make: &'static str,
    pub model: &'static str,
    /// XYZ -> camera native under illuminant A and D65 (`ColorMatrix1/2`).
    pub color_matrix: [Mat3; 2],
    /// White-balanced camera -> XYZ D50 under A and D65 (`ForwardMatrix1/2`).
    pub forward_matrix: [Mat3; 2],
    /// Mean and max CIE76 of the D65 forward fit over the 190 training patches.
    pub fit_de76_d65: [f64; 2],
    /// rawtoaces-data file the entry was fitted from.
    pub source: &'static str,
}

/// A colour matrix the file itself carries: white-balanced camera RGB -> linear sRGB (D65).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct FileMatrix {
    /// Rows normalised so that each sums to 1.
    pub camera_to_srgb: Mat3,
    /// Where it came from (e.g. `olympus_makernote_0x1011`).
    pub tag: &'static str,
}

impl FileMatrix {
    /// A matrix whose rows each sum to `scale` (within 1 %) and are finite; rows normalised to 1.
    pub fn from_scaled(values: [f64; 9], scale: f64, tag: &'static str) -> Option<Self> {
        if !scale.is_finite() || scale <= 0.0 || values.iter().any(|v| !v.is_finite()) {
            return None;
        }
        let mut m = [0.0; 9];
        for (r, row) in values.chunks_exact(3).enumerate() {
            let sum: f64 = row.iter().sum();
            if (sum / scale - 1.0).abs() > 0.01 {
                return None;
            }
            for (c, v) in row.iter().enumerate() {
                *m.get_mut(r.checked_mul(3)?.checked_add(c)?)? = v / sum;
            }
        }
        Some(Self { camera_to_srgb: m, tag })
    }
}

/// What a vendor decoder read about colour.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct VendorColour {
    /// IFD0 Make (or the container's maker for formats without one).
    pub make: Option<String>,
    /// Camera-native value of a neutral under the as-shot light (G = 1; DNG AsShotNeutral).
    pub as_shot_neutral: Option<[f64; 3]>,
    /// The tag the neutral came from.
    pub neutral_tag: Option<&'static str>,
    pub file_matrix: Option<FileMatrix>,
}

impl VendorColour {
    /// Neutral from white-balance multipliers (red and blue relative to green); `None` unless both
    /// are finite and within 0.05..20.
    pub fn neutral_from_multipliers(red: f64, blue: f64) -> Option<[f64; 3]> {
        let ok = |v: f64| v.is_finite() && (0.05..=20.0).contains(&v);
        (ok(red) && ok(blue)).then(|| [1.0 / red, 1.0, 1.0 / blue])
    }
}

/// Where a frame's colour came from.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ColourRoute {
    /// DNG colour tags of the file.
    DngTags,
    /// A vendor matrix tag of the file (see [`FileMatrix`]).
    FileMatrix { tag: &'static str },
    /// The spectral table; `alias` is the file's model when it matched through rawtoaces-data's aliases.
    SpectralTable { make: &'static str, model: &'static str, alias: bool },
    /// No matrix: develop refuses `missing_colour_data`.
    None,
}

impl ColourRoute {
    pub fn key(&self) -> &'static str {
        match self {
            Self::DngTags => "dng_tags",
            Self::FileMatrix { .. } => "file_matrix",
            Self::SpectralTable { .. } => "spectral_table",
            Self::None => "none",
        }
    }

    /// A single calibration illuminant (the vendor file matrix): below STU-COL-218's two, so
    /// develop refuses it unless the caller opts in ([`crate::DngRaw::allow_approximate_colour`]).
    pub fn single_illuminant(&self) -> bool {
        matches!(self, Self::FileMatrix { .. })
    }

    /// The assumption a route makes beyond the file's numbers (`None` when it makes none).
    pub fn assumption(&self) -> Option<&'static str> {
        matches!(self, Self::FileMatrix { .. }).then_some("file_matrix_white_assumed_d65")
    }
}

fn words(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ").to_lowercase()
}

/// Table make for a file make: rawtoaces-data make aliases, else the first word, case-insensitive.
fn make_key(make: &str) -> String {
    let full = words(make);
    for (from, to) in table::MAKE_ALIASES {
        if words(from) == full {
            return words(to);
        }
    }
    full.split(' ').next().unwrap_or("").to_string()
}

/// Model without a leading make word ("Canon EOS R6" -> "eos r6", "NIKON Z 6" -> "z 6").
fn model_key(model: &str, make: &str) -> String {
    let m = words(model);
    match m.strip_prefix(make).and_then(|rest| rest.strip_prefix(' ')) {
        Some(rest) if !make.is_empty() => rest.to_string(),
        _ => m,
    }
}

/// The spectral-table entry for `make` / `model` (exact, then rawtoaces-data alias) and whether
/// it matched through an alias.
pub fn spectral_camera(make: &str, model: &str) -> Option<(&'static SpectralCamera, bool)> {
    let mk = make_key(make);
    let md = model_key(model, &mk);
    let find = |mk: &str, md: &str| table::CAMERAS.iter().find(|c| words(c.make) == mk && words(c.model) == md);
    if let Some(c) = find(&mk, &md) {
        return Some((c, false));
    }
    table::ALIASES
        .iter()
        .find(|(amake, amodel, ..)| make_key(amake) == mk && words(amodel) == md)
        .and_then(|(_, _, tmake, tmodel, _)| find(&make_key(tmake), &words(tmodel)))
        .map(|c| (c, true))
}

/// Every table entry (for listing and tests).
pub fn spectral_cameras() -> &'static [SpectralCamera] {
    table::CAMERAS
}

/// The DNG colour of a vendor frame and its route (file matrix first, then the spectral table).
pub(crate) fn resolve(vendor: &VendorColour, model: Option<&str>) -> (DngColor, ColourRoute) {
    let mut color = DngColor::empty();
    color.as_shot_neutral = vendor.as_shot_neutral;
    if let Some(fm) = vendor.file_matrix {
        let forward = color::mul(&SRGB_TO_XYZ_D50, &fm.camera_to_srgb);
        color.forward_matrix = [Some(forward), None];
        color.calibration_illuminant = [Some(21), None];
        if let Some(n) = vendor.as_shot_neutral
            && let Ok(adapt) = color::bradford(&D50_XYZ, &D65_XYZ)
            && let Ok(inv) = color::invert(&color::mul(&adapt, &forward))
        {
            color.color_matrix = [Some(color::mul(&color::diag(n), &inv)), None];
        }
        return (color, ColourRoute::FileMatrix { tag: fm.tag });
    }
    if let (Some(make), Some(model)) = (vendor.make.as_deref(), model)
        && let Some((cam, alias)) = spectral_camera(make, model)
    {
        color.color_matrix = cam.color_matrix.map(Some);
        color.forward_matrix = cam.forward_matrix.map(Some);
        color.calibration_illuminant = TABLE_ILLUMINANTS.map(Some);
        return (color, ColourRoute::SpectralTable { make: cam.make, model: cam.model, alias });
    }
    (color, ColourRoute::None)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_lookup_by_make_model_and_alias() {
        let (r6, alias) = spectral_camera("Canon", "Canon EOS R6").unwrap();
        assert_eq!((r6.model, alias), ("EOS R6", false));
        assert_eq!(spectral_camera("NIKON CORPORATION", "NIKON Z f").map(|(c, a)| (c.model, a)), Some(("Z f", false)));
        // rawtoaces-data alias (same sensor): Z 6_2 -> Z f.
        assert_eq!(spectral_camera("NIKON CORPORATION", "NIKON Z 6_2").map(|(c, a)| (c.model, a)), Some(("Z f", true)));
        for (make, model) in [("NIKON CORPORATION", "NIKON Z 6"), ("NIKON CORPORATION", "NIKON D70s"), ("FUJIFILM", "X-S10"), ("Panasonic", "DMC-LX7"), ("", "EOS R6")] {
            assert!(spectral_camera(make, model).is_none(), "{make} {model}");
        }
        // Every entry: a white-balanced (1, 1, 1) maps to the D50 white; each ColorMatrix is invertible.
        for c in spectral_cameras() {
            for fm in c.forward_matrix {
                let w = color::mul_vec(&fm, &[1.0; 3]);
                assert!(w.iter().zip(D50_XYZ).all(|(a, b)| (a - b).abs() < 2e-5), "{} {w:?}", c.model);
            }
            for cm in c.color_matrix {
                assert!(color::invert(&cm).is_ok(), "{}", c.model);
            }
        }
    }

    /// STU-COL-218: the two table calibrations (A, D65) are interpolated by the estimated scene
    /// CCT, linear in mired, for ColorMatrix and ForwardMatrix alike.
    #[test]
    fn table_profiles_interpolate_between_their_two_illuminants_by_cct() {
        let (r6, _) = spectral_camera("Canon", "Canon EOS R6").unwrap();
        let neutral_under = |cm: &Mat3, xy: [f64; 2]| {
            let n = color::mul_vec(cm, &color::xy_to_xyz(xy));
            [n[0] / n[1], 1.0, n[2] / n[1]]
        };
        let (a_xy, d65_xy) = ([0.44757, 0.40745], [0.31271, 0.32902]);
        let solve = |n: [f64; 3]| {
            let vendor = VendorColour { make: Some("Canon".into()), as_shot_neutral: Some(n), ..Default::default() };
            color::solve(&resolve(&vendor, Some("EOS R6")).0).unwrap()
        };
        let na = neutral_under(&r6.color_matrix[0], a_xy);
        let nd = neutral_under(&r6.color_matrix[1], d65_xy);
        let (sa, sd) = (solve(na), solve(nd));
        assert!(sa.weight < 1e-3 && (sa.cct - 2856.0).abs() < 15.0, "A: w {} cct {}", sa.weight, sa.cct);
        assert!(sd.weight > 1.0 - 1e-3 && (sd.cct - 6504.0).abs() < 15.0, "D65: w {} cct {}", sd.weight, sd.cct);
        // Between: weight strictly inside, mired-linear in the solved CCT, and the camera matrix is
        // the weight's blend of the two ForwardMatrices times the white-balance diagonal.
        let mut last_cct = sa.cct;
        for t in [0.2, 0.4, 0.6, 0.8] {
            let n = [na[0].powf(1.0 - t) * nd[0].powf(t), 1.0, na[2].powf(1.0 - t) * nd[2].powf(t)];
            let s = solve(n);
            assert!(s.weight > 0.0 && s.weight < 1.0 && s.cct > last_cct, "t {t}: w {} cct {}", s.weight, s.cct);
            last_cct = s.cct;
            let w = (1.0 / s.cct - 1.0 / 2856.0) / (1.0 / 6504.0 - 1.0 / 2856.0);
            assert!((w - s.weight).abs() < 1e-9, "t {t}: {w} vs {}", s.weight);
            let mut fm = [0.0; 9];
            for (i, v) in fm.iter_mut().enumerate() {
                *v = (1.0 - s.weight) * r6.forward_matrix[0][i] + s.weight * r6.forward_matrix[1][i];
            }
            let want = color::mul(&fm, &color::diag([1.0 / n[0], 1.0, 1.0 / n[2]]));
            assert!(want.iter().zip(s.camera_to_xyz_d50).all(|(a, b)| (a - b).abs() < 1e-9), "t {t}");
        }
    }

    #[test]
    fn file_matrix_rows_must_sum_to_the_scale() {
        let olympus = [372.0, -116.0, 0.0, -58.0, 404.0, -90.0, -2.0, -135.0, 393.0];
        let m = FileMatrix::from_scaled(olympus, 256.0, "t").unwrap();
        for row in m.camera_to_srgb.chunks_exact(3) {
            assert!((row.iter().sum::<f64>() - 1.0).abs() < 1e-12);
        }
        let mut bad = olympus;
        bad[0] = 400.0;
        assert!(FileMatrix::from_scaled(bad, 256.0, "t").is_none());
        assert!(FileMatrix::from_scaled([f64::NAN; 9], 256.0, "t").is_none());
        assert!(FileMatrix::from_scaled(olympus, 0.0, "t").is_none());
    }

    #[test]
    fn resolved_colour_solves_and_keeps_a_neutral_neutral() {
        // Spectral route: as-shot neutral -> D50 white.
        let vendor = VendorColour { make: Some("Canon".into()), as_shot_neutral: Some([0.5, 1.0, 0.7]), ..Default::default() };
        let (c, route) = resolve(&vendor, Some("Canon EOS R6"));
        assert_eq!(route.key(), "spectral_table");
        let s = color::solve(&c).unwrap();
        let w = color::mul_vec(&s.camera_to_xyz_d50, &[0.5, 1.0, 0.7]);
        assert!(w.iter().zip(D50_XYZ).all(|(a, b)| (a - b).abs() < 5e-5), "{w:?}");
        // File-matrix route: the same, and the solved white is D65 by construction.
        let fm = FileMatrix::from_scaled([372.0, -116.0, 0.0, -58.0, 404.0, -90.0, -2.0, -135.0, 393.0], 256.0, "t");
        let vendor = VendorColour { file_matrix: fm, as_shot_neutral: Some([0.6, 1.0, 0.62]), ..Default::default() };
        let (c, route) = resolve(&vendor, None);
        assert_eq!((route.key(), route.assumption()), ("file_matrix", Some("file_matrix_white_assumed_d65")));
        let s = color::solve(&c).unwrap();
        let w = color::mul_vec(&s.camera_to_xyz_d50, &[0.6, 1.0, 0.62]);
        assert!(w.iter().zip(D50_XYZ).all(|(a, b)| (a - b).abs() < 5e-5), "{w:?}");
        assert!((s.cct - 6504.0).abs() < 60.0, "{}", s.cct);
        // No matrix: the neutral alone still refuses.
        let vendor = VendorColour { make: Some("Panasonic".into()), as_shot_neutral: Some([0.5, 1.0, 0.5]), ..Default::default() };
        let (c, route) = resolve(&vendor, Some("DMC-LX7"));
        assert_eq!(route, ColourRoute::None);
        assert_eq!(color::solve(&c).err(), Some(crate::DevelopError::MissingColourData));
        assert_eq!(VendorColour::neutral_from_multipliers(2.0, 0.0), None);
        assert_eq!(VendorColour::neutral_from_multipliers(2.0, 1.25), Some([0.5, 1.0, 0.8]));
    }
}
