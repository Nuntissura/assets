/// The index options (every field of the STU-LAY-149 table). No `Default`: the spec declares no
/// default for any field.
#[derive(Clone, Debug, PartialEq)]
pub struct IndexOptions {
    pub title: String,
    pub title_style: Option<ParagraphStyleRef>,
    /// Replaces CONTENT only; the index story keeps its id and other properties. The three include
    /// booleans are `None` when unknown (no spec default); generation needs them stated.
    pub replace_existing_index: Option<bool>,
    pub include_book_documents: Option<bool>,
    pub include_hidden_entries: Option<bool>,
    /// Governs level 2 and lower.
    pub index_format: IndexFormat,
    pub include_section_headings: bool,
    /// Valid only when section headings are on.
    pub include_empty_index_sections: bool,
    pub level_1_style: Option<ParagraphStyleRef>,
    pub level_2_style: Option<ParagraphStyleRef>,
    pub level_3_style: Option<ParagraphStyleRef>,
    pub level_4_style: Option<ParagraphStyleRef>,
    pub section_heading_style: Option<ParagraphStyleRef>,
    pub page_number_style: Option<CharacterStyleRef>,
    pub cross_reference_style: Option<CharacterStyleRef>,
    pub cross_reference_topic_style: Option<CharacterStyleRef>,
    pub following_topic_separator: String,
    pub between_entries_separator: String,
    pub page_range_separator: String,
    pub between_page_numbers_separator: String,
    pub before_cross_reference_separator: String,
    pub entry_end_separator: String,
}
impl IndexOptions {
    /// The persisted Folio options read as this record (every persisted value, unknown kept
    /// unknown). The header-set reference is not an options-table field: [`PersistedIndexOptions`]
    /// keeps it.
    pub fn from_folio(o: &StudioIndexOptions) -> Result<Self, IndexCommandError> {
        if o.level_styles.len() > STUDIO_MAX_INDEX_LEVELS {
            return Err(IndexCommandError::Layout(LayoutError::InvalidInput));
        }
        let para = |v: &Option<String>| v.as_deref().map(ParagraphStyleRef::parse).transpose().map_err(|_| IndexCommandError::StyleRef);
        let chr = |v: &Option<String>| v.as_deref().map(CharacterStyleRef::parse).transpose().map_err(|_| IndexCommandError::StyleRef);
        let level = |k: usize| {
            o.level_styles.get(k).and_then(|s| s.as_deref()).map(ParagraphStyleRef::parse).transpose().map_err(|_| IndexCommandError::StyleRef)
        };
        Ok(Self {
            title: o.title.clone(),
            title_style: para(&o.title_style)?,
            replace_existing_index: o.replace_existing_index,
            include_book_documents: o.include_book_documents,
            include_hidden_entries: o.include_hidden_entries,
            index_format: o.index_format,
            include_section_headings: o.include_section_headings,
            include_empty_index_sections: o.include_empty_index_sections,
            level_1_style: level(0)?,
            level_2_style: level(1)?,
            level_3_style: level(2)?,
            level_4_style: level(3)?,
            section_heading_style: para(&o.section_heading_style)?,
            page_number_style: chr(&o.page_number_style)?,
            cross_reference_style: chr(&o.cross_reference_style)?,
            cross_reference_topic_style: chr(&o.cross_reference_topic_style)?,
            following_topic_separator: o.following_topic_separator.clone(),
            between_entries_separator: o.between_entries_separator.clone(),
            page_range_separator: o.page_range_separator.clone(),
            between_page_numbers_separator: o.between_page_numbers_separator.clone(),
            before_cross_reference_separator: o.before_cross_reference_separator.clone(),
            entry_end_separator: o.entry_end_separator.clone(),
        })
    }
    /// This record as persisted Folio options naming `section_header_set` (the inverse of
    /// [`IndexOptions::from_folio`]; level styles are written up to the deepest set one).
    pub fn to_folio(&self, section_header_set: Option<&str>) -> StudioIndexOptions {
        let para = |r: &Option<ParagraphStyleRef>| r.as_ref().map(|r| r.as_str().to_owned());
        let chr = |r: &Option<CharacterStyleRef>| r.as_ref().map(|r| r.as_str().to_owned());
        let mut level_styles: Vec<Option<String>> =
            [&self.level_1_style, &self.level_2_style, &self.level_3_style, &self.level_4_style].into_iter().map(para).collect();
        while level_styles.last().is_some_and(Option::is_none) {
            level_styles.pop();
        }
        StudioIndexOptions {
            title: self.title.clone(),
            title_style: para(&self.title_style),
            index_format: self.index_format,
            include_section_headings: self.include_section_headings,
            include_empty_index_sections: self.include_empty_index_sections,
            level_styles,
            section_heading_style: para(&self.section_heading_style),
            following_topic_separator: self.following_topic_separator.clone(),
            between_entries_separator: self.between_entries_separator.clone(),
            page_range_separator: self.page_range_separator.clone(),
            between_page_numbers_separator: self.between_page_numbers_separator.clone(),
            before_cross_reference_separator: self.before_cross_reference_separator.clone(),
            entry_end_separator: self.entry_end_separator.clone(),
            replace_existing_index: self.replace_existing_index,
            include_book_documents: self.include_book_documents,
            include_hidden_entries: self.include_hidden_entries,
            page_number_style: chr(&self.page_number_style),
            cross_reference_style: chr(&self.cross_reference_style),
            cross_reference_topic_style: chr(&self.cross_reference_topic_style),
            section_header_set: section_header_set.map(str::to_owned),
        }
    }
    /// The three include booleans, each stated (`index_flag_unset` names the first unknown one).
    pub fn stated_flags(&self) -> Result<IndexFlags, IndexCommandError> {
        let flag = |v: Option<bool>, name: &'static str| v.ok_or(IndexCommandError::FlagUnset(name));
        Ok(IndexFlags {
            replace_existing_index: flag(self.replace_existing_index, "replace_existing_index")?,
            include_book_documents: flag(self.include_book_documents, "include_book_documents")?,
            include_hidden_entries: flag(self.include_hidden_entries, "include_hidden_entries")?,
        })
    }
    /// The six separators in table order (independent strings).
    pub fn separators(&self) -> [&str; 6] {
        [
            &self.following_topic_separator,
            &self.between_entries_separator,
            &self.page_range_separator,
            &self.between_page_numbers_separator,
            &self.before_cross_reference_separator,
            &self.entry_end_separator,
        ]
    }
    /// The paragraph style of topic level `depth` (0-based).
    pub fn level_style(&self, depth: usize) -> Option<&ParagraphStyleRef> {
        [&self.level_1_style, &self.level_2_style, &self.level_3_style, &self.level_4_style].get(depth).and_then(|s| s.as_ref())
    }
    /// Separators of at most 100 characters without a line break or control character
    /// (`index_separator`), empty sections only with headings, a bounded title, style references
    /// of their scope when type-style records are given.
    pub fn check(&self, styles: Option<&StudioTypeStyleRecords>) -> Result<(), IndexCommandError> {
        if self.separators().iter().any(|s| s.chars().count() > 100 || s.chars().any(char::is_control)) {
            return Err(IndexCommandError::Separator);
        }
        if self.include_empty_index_sections && !self.include_section_headings {
            return Err(IndexCommandError::EmptySectionsWithoutHeadings);
        }
        if self.title.len() > 1024 || self.title.chars().any(char::is_control) {
            return Err(IndexCommandError::Title);
        }
        let para = [
            &self.title_style,
            &self.level_1_style,
            &self.level_2_style,
            &self.level_3_style,
            &self.level_4_style,
            &self.section_heading_style,
        ];
        for r in para.into_iter().flatten() {
            style_scope_ok(styles, r.as_str(), TypeStyleScope::Paragraph).map_err(IndexCommandError::StyleRecord)?;
        }
        for r in [&self.page_number_style, &self.cross_reference_style, &self.cross_reference_topic_style].into_iter().flatten() {
            style_scope_ok(styles, r.as_str(), TypeStyleScope::Character).map_err(IndexCommandError::StyleRecord)?;
        }
        Ok(())
    }
}

