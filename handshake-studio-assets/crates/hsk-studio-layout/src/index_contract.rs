//! Index contract (lane SMB-ID-TOC-INDEX-1; STU-LAY-045, STU-LAY-149): the full index-options record
//! (every field of the table, six independent separators), per-reference page-range scopes, the
//! eight cross-reference types and four capitalisation members by their captured codes, a pluggable
//! section-header-set model, the five captured index typed errors and the attributed generate and
//! update commands. The older `generate_index` (Folio options, no attribution) is kept for its
//! callers. Persistence (lane SMB-ID-TOC-PERSIST-1): Folio's `StudioIndexOptions`, marks and
//! `StudioSectionHeaderSet` carry every field; [`PersistedIndexOptions`],
//! [`PageRangeScope::from_folio`] / [`PageRangeScope::to_folio`] and
//! [`SectionHeaderSet::from_folio`] / [`SectionHeaderSet::to_folio`] are lossless both ways, and a
//! mark's persisted scope is read by the generator. The three include booleans have no spec
//! default: `None` (unknown) is carried and generation refuses it (`index_flag_unset`).
//!
//! Rules (Studio readings; InDesign parity UNVERIFIED, D5):
//! - Levels: Studio's declared maximum is [`STUDIO_MAX_INDEX_LEVELS`] = 4, the captured model's
//!   exact count (STU-LAY-149 permits more; Folio marks carry four).
//! - A mark's page is the page of the frame holding the line of the mark byte (`toc::line_of`): the line
//!   whose source span contains it, a glyph-less mark where a line breaks taking the line the R54
//!   F-R54-6 rule gives it, a mark in a paragraph with no glyph its blank line. Marks in overset text are left out and counted (`unplaced`); marks on
//!   a hidden frame layer are left out and counted (`omitted_hidden`) unless
//!   `include_hidden_entries`.
//! - Page-range scopes ([`PageRangeScope`]; STU-LAY-149 lists none, the members are MT-174's):
//!   current page; to the next paragraph-style change; to the next use of a named paragraph style;
//!   to the end of the story, the document or the page's section; for the next N paragraphs
//!   (counting the mark's own). The range ends on the page of the last byte it covers (overset end:
//!   the story's last placed page). A range of one page prints as that page.
//! - References of a topic: distinct single pages in document order, three or more consecutive
//!   pages collapsing to `first + page_range_separator + last` (as `generate_index`), and scoped
//!   ranges as `first + page_range_separator + last`; items ordered by first page and joined by
//!   `between_page_numbers_separator`. Page numbers carry `page_number_style`.
//! - Cross references follow the page references after `before_cross_reference_separator`; the
//!   lead-in words are `generate_index`'s ("See", "See also", "See herein", "See also herein",
//!   "See [also]"; custom text before or after the target) and carry `cross_reference_style`, the
//!   target topic path (levels joined by ": ") carries `cross_reference_topic_style`.
//! - Nested format: one paragraph per topic with its level style; run-in: level 2 and deeper
//!   continue their level-1 paragraph after `between_entries_separator` (`index_format` governs
//!   level 2 and lower).
//! - Section headings from the header set (Latin when none is given): level-1 topics are ordered by
//!   header group (header-set order), then by sort key; a heading precedes the first topic of each
//!   group, and every group's heading is written with `include_empty_index_sections` (valid only
//!   with headings). A topic matches the group listing its lower-cased first character, else the
//!   first catch-all group (empty initials); a topic in no group precedes every heading.
//! - `replace_existing_index` with an existing index story replaces CONTENT only (story id, text
//!   kind, direction kept); otherwise the index is a new story.
//! - Capitalisation ([`capitalize_index_topics`]): the first character of the affected topics is
//!   upper-cased; `selected_entry` / `include_subentries` are refused for a whole index.
//!
//! Captured typed errors: `index_invalid_page_entry`, `index_invalid_topic_entry`,
//! `index_invalid_referenced_topic_entry`, `index_story_locked` (the index story, or a story it
//! reads, is locked), `book_document_missing`; plus `index_separator` (an invalid separator set).
//! Hostile input: marks, scopes, header groups and initials, generated bytes are bounded.
