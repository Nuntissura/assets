//! Index generation (STU-LAY-045, STU-LAY-149): Folio index marks become a generated story with a
//! topic/subtopic hierarchy of up to four levels, page references from the layout placements and
//! cross references; the caller places and composes it like any story.
//!
//! Rules (documented; InDesign parity UNVERIFIED, D5):
//! - A mark's page is the page of the frame holding the first line whose source span contains (or
//!   starts at) the mark byte (as the TOC); marks in overset text are left out and counted
//!   (`GeneratedIndex::unplaced`).
//! - Topics merge by their text per level; siblings sort by the lower-cased sort-by text (the topic
//!   text when no sort-by is given), ties by the topic text. Page references of a topic are its
//!   distinct pages in document order joined by `between_page_numbers_separator`; three or more
//!   consecutive document pages become `first + page_range_separator + last`.
//! - Cross references follow the page numbers after `before_cross_reference_separator`: see ->
//!   "See " + target, see_also -> "See also ", see_herein -> "See herein ", see_also_herein ->
//!   "See also herein ", see_or_also_bracket -> "See [also] ", custom / custom_before -> custom text
//!   + " " + target, custom_after -> target + " " + custom text; target levels joined by ": ".
//! - Nested format: one paragraph per topic with its level style; text = topic +
//!   `following_topic_separator` + references + `entry_end_separator` (the separator only when
//!   there are references). Run-in: level 2 and deeper topics continue their level-1 paragraph,
//!   each after `between_entries_separator`.
//! - Section headings (Latin header set by default; [`HeaderGroup`] lists make it pluggable): a
//!   heading paragraph before the first level-1 topic of each group; with empty sections every
//!   group's heading is written. Topics whose first letter is in no group go under the first group
//!   with an empty letter list (or, absent, before all headings).
//!
//! Hostile input: Folio `check_index_marks` / `check_index_options` (levels, sort-by, xref custom
//! text, separators); marks and generated bytes are bounded (`IndexLimits`), checked before use.
#![deny(clippy::arithmetic_side_effects)]
use crate::LayoutError;
use crate::numbering::PageNumber;
use crate::toc::{TocSource, Writer, page_of};
use hsk_studio_accord::CancellationToken;
use hsk_studio_folio::{
    IndexFormat, IndexXrefKind, StudioDocument, StudioIndexMark, StudioIndexOptions,
    check_index_marks, check_index_options,
};
use std::collections::{BTreeMap, BTreeSet};

/// One section-heading group of a header set.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct HeaderGroup {
    pub heading: String,
    /// Lower-case initials that belong to the group; empty = the catch-all group.
    pub initials: Vec<char>,
}

/// The Latin header set: "Symbols" (catch-all) then A..Z.
pub fn latin_headers() -> Vec<HeaderGroup> {
    let mut v = vec![HeaderGroup { heading: "Symbols".into(), initials: Vec::new() }];
    v.extend((b'a'..=b'z').map(|c| HeaderGroup {
        heading: char::from(c).to_ascii_uppercase().to_string(),
        initials: vec![char::from(c)],
    }));
    v
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct IndexLimits {
    pub max_marks: usize,
    pub max_text_bytes: usize,
}
impl Default for IndexLimits {
    fn default() -> Self {
        Self { max_marks: 262_144, max_text_bytes: 16 << 20 }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum IndexError {
    /// Folio index rule (`index_topic_levels`, `index_separator`, ...).
    Marks(&'static str),
    BudgetExceeded,
    Layout(LayoutError),
}
impl IndexError {
    pub const fn code(self) -> &'static str {
        match self {
            Self::Marks(w) => w,
            Self::BudgetExceeded => "budget_exceeded",
            Self::Layout(e) => e.code(),
        }
    }
}
impl std::fmt::Display for IndexError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.code())
    }
}
impl std::error::Error for IndexError {}

/// The generated index story plus how many marks were not placed.
#[derive(Clone, Debug, PartialEq)]
pub struct GeneratedIndex {
    pub story: crate::toc::GeneratedStory,
    pub unplaced: usize,
}

#[derive(Default)]
struct Topic {
    /// (document ordinal, label) of each referenced page.
    pages: BTreeSet<(usize, String)>,
    xrefs: Vec<String>,
    children: BTreeMap<(String, String), Topic>,
}

fn xref_text(kind: IndexXrefKind, target: &[String], custom: Option<&str>) -> String {
    let t = target.join(": ");
    let c = custom.unwrap_or("");
    match kind {
        IndexXrefKind::See => format!("See {t}"),
        IndexXrefKind::SeeAlso => format!("See also {t}"),
        IndexXrefKind::SeeHerein => format!("See herein {t}"),
        IndexXrefKind::SeeAlsoHerein => format!("See also herein {t}"),
        IndexXrefKind::SeeOrAlsoBracket => format!("See [also] {t}"),
        IndexXrefKind::Custom | IndexXrefKind::CustomBefore => format!("{c} {t}"),
        IndexXrefKind::CustomAfter => format!("{t} {c}"),
    }
}

fn references(t: &Topic, o: &StudioIndexOptions) -> String {
    let pages: Vec<&(usize, String)> = t.pages.iter().collect();
    let mut parts: Vec<String> = Vec::new();
    let mut i = 0usize;
    while let Some(first) = pages.get(i) {
        let mut j = i;
        while let (Some(a), Some(b)) = (pages.get(j), pages.get(j.saturating_add(1))) {
            if a.0.checked_add(1) != Some(b.0) {
                break;
            }
            j = j.saturating_add(1);
        }
        if j.saturating_sub(i) >= 2 {
            let last = pages.get(j).map_or("", |p| p.1.as_str());
            parts.push(format!("{}{}{last}", first.1, o.page_range_separator));
        } else {
            parts.extend(pages[i..=j].iter().map(|p| p.1.clone()));
        }
        i = j.saturating_add(1);
    }
    let mut s = parts.join(&o.between_page_numbers_separator);
    if !t.xrefs.is_empty() {
        if !s.is_empty() {
            s.push_str(&o.before_cross_reference_separator);
        }
        s.push_str(&t.xrefs.join(&o.before_cross_reference_separator));
    }
    s
}

/// Generates the index (module docs). `headers` = `None` uses [`latin_headers`].
#[allow(clippy::too_many_arguments)]
pub fn generate_index(
    document: &StudioDocument,
    options: &StudioIndexOptions,
    marks: &[StudioIndexMark],
    sources: &[TocSource<'_>],
    pages: &[PageNumber],
    headers: Option<&[HeaderGroup]>,
    limits: IndexLimits,
    cancel: &CancellationToken,
) -> Result<GeneratedIndex, IndexError> {
    cancel.check().map_err(|_| IndexError::Layout(LayoutError::Canceled))?;
    if marks.len() > limits.max_marks {
        return Err(IndexError::BudgetExceeded);
    }
    check_index_marks(marks).map_err(IndexError::Marks)?;
    check_index_options(options).map_err(IndexError::Marks)?;
    for s in sources {
        if s.placement.is_some_and(|p| p.base_revision != document.revision) {
            return Err(IndexError::Layout(LayoutError::StaleRevision {
                expected: s.placement.map_or(0, |p| p.base_revision),
                current: document.revision,
            }));
        }
    }
    let by_page: BTreeMap<(usize, usize), &PageNumber> = pages.iter().map(|p| ((p.spread, p.page), p)).collect();
    let mut root: BTreeMap<(String, String), Topic> = BTreeMap::new();
    let mut unplaced = 0usize;
    for (k, m) in marks.iter().enumerate() {
        if k.is_multiple_of(1024) {
            cancel.check().map_err(|_| IndexError::Layout(LayoutError::Canceled))?;
        }
        let source = sources.iter().find(|s| s.story.story_id == m.story_id);
        let page = source.and_then(|s| page_of(s.placement, m.at, &by_page));
        if page.is_none() && m.xref.is_none() {
            unplaced = unplaced.saturating_add(1);
            continue;
        }
        let mut level = &mut root;
        let mut node: Option<&mut Topic> = None;
        let deepest = m.topics.len().saturating_sub(1);
        for (d, topic) in m.topics.iter().enumerate() {
            let sort = m.sort_by.get(d).filter(|s| !s.is_empty()).unwrap_or(topic).to_lowercase();
            let entry = level.entry((sort, topic.clone())).or_default();
            if d == deepest {
                node = Some(entry);
                break;
            }
            level = &mut entry.children;
        }
        let Some(n) = node else { continue };
        if let Some(p) = page {
            n.pages.insert((p.ordinal, p.label.clone()));
        }
        if let Some(x) = &m.xref {
            let text = xref_text(x.kind, &x.target, x.custom_text.as_deref());
            if !n.xrefs.contains(&text) {
                n.xrefs.push(text);
            }
        }
    }
    let latin;
    let headers = match headers {
        Some(h) => h,
        None => {
            latin = latin_headers();
            &latin
        }
    };
    let group_of = |topic: &str| -> Option<usize> {
        let c = topic.chars().next()?.to_lowercase().next()?;
        headers
            .iter()
            .position(|g| g.initials.contains(&c))
            .or_else(|| headers.iter().position(|g| g.initials.is_empty()))
    };
    let mut w = Writer::new(limits.max_text_bytes);
    let push = |w: &mut Writer, text: &str, style: Option<&str>| w.push(text, style).map_err(|_| IndexError::BudgetExceeded);
    if !options.title.is_empty() {
        push(&mut w, &options.title, options.title_style.as_deref())?;
    }
    let level_style = |d: usize| options.level_styles.get(d).and_then(|s| s.as_deref());
    let mut written_group: Option<usize> = None;
    let heading_style = options.section_heading_style.as_deref();
    let emit_headings_until = |w: &mut Writer, upto: Option<usize>, written: &mut Option<usize>| -> Result<(), IndexError> {
        if !options.include_section_headings {
            return Ok(());
        }
        let Some(g) = upto else { return Ok(()) };
        let start = written.map_or(0, |x| x.saturating_add(1));
        for k in start..=g {
            if (options.include_empty_index_sections || k == g)
                && let Some(h) = headers.get(k)
            {
                push(w, &h.heading, heading_style)?;
            }
        }
        if written.is_none_or(|x| x < g) {
            *written = Some(g);
        }
        Ok(())
    };
    fn walk(
        level: &BTreeMap<(String, String), Topic>,
        depth: usize,
        o: &StudioIndexOptions,
        out: &mut Vec<(usize, String, String)>,
    ) {
        for ((_, topic), t) in level {
            let refs = references(t, o);
            out.push((depth, topic.clone(), refs));
            walk(&t.children, depth.saturating_add(1), o, out);
        }
    }
    let mut flat: Vec<(usize, String, String)> = Vec::new();
    walk(&root, 0, options, &mut flat);
    let mut run_in: Option<(String, Option<&str>)> = None;
    for (k, (depth, topic, refs)) in flat.iter().enumerate() {
        if k.is_multiple_of(256) {
            cancel.check().map_err(|_| IndexError::Layout(LayoutError::Canceled))?;
        }
        let mut entry = topic.clone();
        if !refs.is_empty() {
            entry.push_str(&options.following_topic_separator);
            entry.push_str(refs);
            entry.push_str(&options.entry_end_separator);
        }
        if *depth == 0 {
            if let Some((text, style)) = run_in.take() {
                push(&mut w, &text, style)?;
            }
            emit_headings_until(&mut w, group_of(topic), &mut written_group)?;
        }
        match options.index_format {
            IndexFormat::Nested => push(&mut w, &entry, level_style(*depth))?,
            IndexFormat::RunIn => match (&mut run_in, *depth) {
                (Some((text, _)), d) if d > 0 => {
                    text.push_str(&options.between_entries_separator);
                    text.push_str(&entry);
                    if text.len() > limits.max_text_bytes {
                        return Err(IndexError::BudgetExceeded);
                    }
                }
                _ => run_in = Some((entry, level_style(0))),
            },
        }
    }
    if let Some((text, style)) = run_in.take() {
        push(&mut w, &text, style)?;
    }
    if options.include_section_headings && options.include_empty_index_sections {
        let last = headers.len().checked_sub(1);
        emit_headings_until(&mut w, last, &mut written_group)?;
    }
    Ok(GeneratedIndex {
        story: crate::toc::GeneratedStory { text: w.text, paragraphs: w.paragraphs, entries: Vec::new() },
        unplaced,
    })
}
